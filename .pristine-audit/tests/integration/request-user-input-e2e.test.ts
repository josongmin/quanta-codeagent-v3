/**
 * ADR-0097 (Tier-S6) — `request_user_input` end-to-end.
 *
 * Drives the full `runAgent` loop with a `ScriptedLLM` that issues a
 * `request_user_input` tool_use, then asserts:
 *   - the tool is REGISTERED iff `AgentConfig.userInputPort` is wired;
 *   - the host-port mock is INVOKED with the model's question + choices;
 *   - the operator's "answer" outcome is mirrored into the assistant's
 *     subsequent `tool_result` block as `ok:true` + the answer text;
 *   - the "cancelled" outcome is mirrored as a typed `rejected` failure
 *     (`is_error: true`, "User cancelled" surfaced);
 *   - absent port ⇒ tool NOT in the registry, dispatch returns a deny
 *     tool_result ("Unknown tool: request_user_input") and the loop is
 *     otherwise byte-identical.
 *
 * Sister to the `request_plan_exit` host-port wire — exercises the same
 * `ToolContext.requestUserInput` seam via the real dispatch path.
 */

import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { mkdtempSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { runAgent } from "@/agent"
import type { PermissionContext } from "@/permission"
import {
  defaultTools,
  requestUserInputTool,
  ToolRegistry,
  type UserInputOutcome,
  type UserInputRequester,
} from "@/tool"
import {
  ev as evStep,
  baseConfig as harnessBaseConfig,
  RecordingStream,
  ScriptedLLM,
  text as textScript,
  toolUse as toolUseScript,
} from "./_harness"

const cfgWith = (over: Partial<import("@/agent").AgentConfig>): import("@/agent").AgentConfig =>
  harnessBaseConfig({
    permission: { mode: "acceptEdits" } as PermissionContext,
    maxTurns: 10,
    system: "test",
    ...over,
  })

describe("request_user_input — end-to-end via runAgent (ADR-0097)", () => {
  let dir: string
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "rui-e2e-"))
  })
  afterEach(() => {
    rmSync(dir, { recursive: true, force: true })
  })

  test("port wired + answer outcome ⇒ tool_result carries the operator's reply", async () => {
    // Script: turn 1 ⇒ tool_use(request_user_input), turn 2 ⇒ text("done").
    const llm = new ScriptedLLM([
      evStep(
        toolUseScript("c1", "request_user_input", {
          prompt: "Pick framework",
          choices: ["Next.js", "Remix"],
        }),
      ),
      evStep(textScript("done")),
    ])
    const stream = new RecordingStream()
    // Registry MUST include `request_user_input` because features.ts conditionally
    // registers it when `userInputPort` is set. We mirror that here by building a
    // registry that already contains the tool — runAgent's feature gate will not
    // duplicate registrations, but it WILL refuse to add it unless the port is
    // wired. Adding it eagerly to the registry sidesteps that ordering concern
    // and keeps this test focused on the seam, not on feature-gate plumbing.
    const registry = new ToolRegistry([...defaultTools, requestUserInputTool()])

    // Mock port: records the request the dispatch seam forwards, returns "answer".
    const seen: Array<Parameters<UserInputRequester>[0]> = []
    const userInputPort: UserInputRequester = async (req) => {
      seen.push(req)
      return { decision: "answer", text: "Next.js" } satisfies UserInputOutcome
    }

    const outcome = await runAgent({
      ...cfgWith({ llm, registry, stream, cwd: dir }),
      userInputPort,
    })

    expect(outcome.reason).toBe("completed")

    // (a) Host port received the model's question + choices verbatim.
    expect(seen).toHaveLength(1)
    const req = seen[0]
    expect(req).toBeDefined()
    if (!req) return // narrow for tsc
    expect(req.prompt).toBe("Pick framework")
    expect(req.choices).toEqual(["Next.js", "Remix"])
    // promptId is generated by the tool — should be a non-empty string.
    expect(typeof req.promptId).toBe("string")
    expect(req.promptId.length).toBeGreaterThan(0)

    // (b) tool_result carries the answer text, ok:true.
    const blocks = outcome.messages.flatMap((m) =>
      m.content.filter((b) => b.type === "tool_result"),
    )
    const ok = blocks.find(
      (b) => b.type === "tool_result" && !b.is_error && b.content.includes("Next.js"),
    )
    expect(ok).toBeDefined()
  })

  test("port wired + cancelled outcome ⇒ tool_result is a rejected error", async () => {
    const llm = new ScriptedLLM([
      evStep(toolUseScript("c1", "request_user_input", { prompt: "Confirm migration?" })),
      evStep(textScript("done")),
    ])
    const stream = new RecordingStream()
    const registry = new ToolRegistry([...defaultTools, requestUserInputTool()])

    const userInputPort: UserInputRequester = async () =>
      ({ decision: "cancelled" }) satisfies UserInputOutcome

    const outcome = await runAgent({
      ...cfgWith({ llm, registry, stream, cwd: dir }),
      userInputPort,
    })

    expect(outcome.reason).toBe("completed")

    const blocks = outcome.messages.flatMap((m) =>
      m.content.filter((b) => b.type === "tool_result"),
    )
    const cancelled = blocks.find(
      (b) => b.type === "tool_result" && b.is_error && b.content.includes("User cancelled"),
    )
    expect(cancelled).toBeDefined()
  })

  test("port ABSENT (default-OFF) ⇒ tool not in registry, deny tool_result", async () => {
    // No userInputPort wired. The conditional registration in features.ts means
    // the tool is NOT in the registry; the dispatch seam yields an unknown-tool
    // deny. The model recovers + finishes the next turn — byte-identical to any
    // unknown-tool path.
    const llm = new ScriptedLLM([
      evStep(toolUseScript("c1", "request_user_input", { prompt: "Anything?" })),
      evStep(textScript("done")),
    ])
    const stream = new RecordingStream()
    const registry = new ToolRegistry(defaultTools) // no requestUserInputTool

    const outcome = await runAgent({
      ...cfgWith({ llm, registry, stream, cwd: dir }),
      // userInputPort intentionally undefined
    })

    expect(outcome.reason).toBe("completed")
    const blocks = outcome.messages.flatMap((m) =>
      m.content.filter((b) => b.type === "tool_result"),
    )
    const denied = blocks.find(
      (b) =>
        b.type === "tool_result" &&
        b.is_error &&
        b.content.includes("Unknown tool: request_user_input"),
    )
    expect(denied).toBeDefined()
  })

  test("registered without userInputPort ⇒ tool runs but yields ok:false (no_handler)", async () => {
    // Defensive seam: even if a host accidentally registers the tool without
    // wiring the port, dispatch still routes the call; ctx.requestUserInput is
    // undefined; the tool's graceful-fail branch fires (ok:false, "no user-input
    // port wired"). Loop never throws past it.
    const llm = new ScriptedLLM([
      evStep(toolUseScript("c1", "request_user_input", { prompt: "Q?" })),
      evStep(textScript("done")),
    ])
    const stream = new RecordingStream()
    const registry = new ToolRegistry([...defaultTools, requestUserInputTool()])

    const outcome = await runAgent({
      ...cfgWith({ llm, registry, stream, cwd: dir }),
      // userInputPort intentionally undefined — the tool is registered but the
      // dispatch seam will NOT populate `ctx.requestUserInput`.
    })

    expect(outcome.reason).toBe("completed")
    const blocks = outcome.messages.flatMap((m) =>
      m.content.filter((b) => b.type === "tool_result"),
    )
    const noHandler = blocks.find(
      (b) =>
        b.type === "tool_result" && b.is_error && b.content.includes("no user-input port wired"),
    )
    expect(noHandler).toBeDefined()
  })
})
