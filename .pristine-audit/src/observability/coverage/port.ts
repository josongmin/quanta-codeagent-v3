/**
 * Code coverage observability — typed port (ADR-0165).
 *
 * Closed-port primitive for per-file coverage observability with branch +
 * statement breakdowns on top of the line-only signal `bun test --coverage`
 * surfaces today. The slice feeds samples through the ADR-0144 `MetricSink`
 * so coverage metrics live alongside every other counter/gauge/histogram the
 * operator can query in-process or export to OTel/Prometheus/JSONL.
 *
 * Plane-clean: this module imports ONLY `node:fs/promises` + `node:path` (for
 * the adapter — the port itself imports nothing). No `@/agent`, `@/tool`,
 * `@/llm`. The reporter receives a `MetricSink` BY VALUE through its options;
 * the port file never imports `@/observability/metrics` so a downstream
 * consumer that wants to evaluate a report without recording metrics pays no
 * import cost.
 *
 * Default-OFF: nothing in the loop instantiates a coverage source today. The
 * `coverage_check` tool is the only auto-registered consumer and is itself a
 * caller-invoked surface (the agent decides when to read the coverage JSON).
 *
 * SOTA reference: bun's built-in `bun test --coverage` reports LINE coverage
 * only; nyc/istanbul tracks line+branch+statement but ships as a heavy CLI
 * with no programmatic `MetricSink` integration. This slice adds branch +
 * statement breakdowns AND wires per-file gauges into the typed metrics sink.
 */

/**
 * Per-file coverage data point. All fields are required + readonly — a partial
 * file coverage would let a consumer report 0% by silently dropping a field,
 * defeating the threshold gate.
 *
 * INVARIANT: `linesCovered ≤ lineCount`, same for branches/statements. Percents
 * are pre-computed (NOT derived on read) so consumers don't repeat the
 * `100 * covered / count` arithmetic and accidentally diverge on the
 * count===0 edge case (we resolve as 100% when count===0 — "an empty file
 * is fully covered"; document elsewhere).
 */
export interface FileCoverage {
  /** Absolute path on disk (the V8 source URL is normalized to abs before
   *  surfacing here — see `v8-source.ts`). */
  readonly file: string
  readonly lineCount: number
  readonly linesCovered: number
  /** 0..100 inclusive. Pre-computed; `linesCovered * 100 / lineCount` (or 100
   *  when `lineCount === 0`). */
  readonly linesPercent: number
  readonly branchCount: number
  readonly branchesCovered: number
  readonly branchesPercent: number
  readonly statementCount: number
  readonly statementsCovered: number
  readonly statementsPercent: number
  /** 1-indexed line numbers that have ≥1 V8 byte-range covering the line
   *  but with `count === 0`. Sorted ascending, deduplicated. */
  readonly uncoveredLines: ReadonlyArray<number>
}

/**
 * Aggregate report — files + repo-wide totals. Totals are weighted by
 * `lineCount`/`branchCount`/`statementCount` (not by file count), so a
 * 1000-line file at 50% does not get the same weight as a 10-line file at
 * 100% — the operator sees the percentage of EXECUTED code, not the
 * percentage of FILES that are well-covered.
 */
export interface CoverageReport {
  readonly files: ReadonlyArray<FileCoverage>
  readonly totals: {
    readonly linesPercent: number
    readonly branchesPercent: number
    readonly statementsPercent: number
    /** Number of files in `files` (post node_modules filter). Useful when a
     *  caller wants to display "Coverage across N files" without re-counting. */
    readonly fileCount: number
  }
  /** Epoch ms when the report was generated by the adapter. Plays the same
   *  role as `MetricSample.at` — the registry/sink can correlate by time. */
  readonly generatedAt: number
}

/**
 * Coverage source adapter. Implementations read a V8-shape coverage JSON
 * (from `bun test --coverage` or `node --experimental-vm-modules --coverage`)
 * and surface a typed {@link CoverageReport}.
 *
 * No-throw contract: every failure mode MUST be raised as a typed
 * {@link CoverageError} — never a bare `Error`, never a string. The
 * `coverage_check` tool branches on `err.code` to surface a stable
 * model-facing failure tag.
 */
export interface CoverageSource {
  /** Read raw V8 coverage JSON from `coverageJsonPath` and produce a typed
   *  report. Throws {@link CoverageError} on:
   *    - `json-malformed`: the file is not valid JSON or the V8 shape is missing
   *    - `io-failed`:      the file could not be read (ENOENT, EACCES, etc.)
   *    - `no-coverage-data`: the V8 `result` array is empty (no scripts
   *      were instrumented — usually a misconfigured runner) */
  read(coverageJsonPath: string): Promise<CoverageReport>
}

/**
 * Minimum-required threshold the reporter checks `CoverageReport.totals`
 * against. Each field is independent — a threshold that omits `branchesPercent`
 * means "do not gate on branches". An empty object is a no-op gate (always
 * passes).
 */
export interface CoverageThreshold {
  readonly linesPercent?: number
  readonly branchesPercent?: number
  readonly statementsPercent?: number
}

/**
 * Closed 2-arm verdict the reporter emits. `pass` carries no payload;
 * `fail` carries human-readable reasons (one per crossed threshold, in a
 * stable order) the caller surfaces to the operator/model. Adding a 3rd
 * arm requires an ADR amendment + a compile-error update at every exhaustive
 * switch site.
 */
export type CoverageVerdict =
  | { readonly kind: "pass" }
  | { readonly kind: "fail"; readonly reasons: ReadonlyArray<string> }

/** Closed 3-arm error code union. Adding a 4th code requires an ADR amendment
 *  + a compile-error update at every exhaustive switch site. */
export type CoverageErrorCode = "json-malformed" | "io-failed" | "no-coverage-data"

/**
 * Throwing surface for the adapter. Distinct from `Result<T,E>` because a
 * coverage-source caller (the tool) classifies the failure ONCE at the
 * boundary into a typed `ToolResult` — same posture as the metrics slice's
 * `MetricsError`.
 */
export class CoverageError extends Error {
  readonly code: CoverageErrorCode
  constructor(code: CoverageErrorCode, message: string) {
    super(message)
    this.name = "CoverageError"
    this.code = code
  }
}
