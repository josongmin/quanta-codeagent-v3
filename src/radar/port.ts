/**
 * The 5-method closed port over the radar's proposal queue (ADR-0231).
 *
 * Every adapter (in-memory, jsonl-file, headless stub) implements
 * `RadarStore` byte-identical at the type level — the parity hellgate
 * (HELL-RC-13) keeps the in-memory and jsonl-file adapters interchangeable
 * for any caller.
 *
 * Why a port (not a class hierarchy): the radar must survive a future
 * adapter swap (sqlite-backed, IPC-backed, network-backed) without a
 * single caller change. Holding the surface to FIVE methods — propose,
 * list, set-status, record-engagement, prune — keeps the door open.
 *
 * Unhappy paths are values, not exceptions: `setStatus` and
 * `recordEngagement` return a `Result` so the caller branches on the
 * `ok` field instead of catching. Adapters reserve throwing for adapter-
 * level surprises (jsonl I/O bubbles, etc.), surfaced as `RadarError`.
 */

import type { Result } from "@/shared"
import type { CardStatus, ProposeOpts, RadarCard } from "./types"

/** The reason a `setStatus` / `recordEngagement` call could not complete. */
export type RadarOpError = "not-found" | "not-active"

export interface RadarStore {
  /**
   * Mint a new `RadarCard` from a `ProposeOpts`. The card's `id` is
   * generated by the store, `status` is forced to `"active"`, and
   * `engagementCount` is `0`. Returns the stored, frozen card.
   *
   * The store is free to evict (in-memory: LRU at the configured cap)
   * BEFORE returning — but the returned card is the one just minted.
   */
  proposeCard(opts: ProposeOpts): RadarCard

  /**
   * Snapshot of every card whose `status === "active"`. The returned
   * array is `Object.freeze`-d and every element is also frozen, so
   * direct mutation throws under strict mode. Ordering is by
   * `createdAtMs` ascending.
   */
  listActive(): readonly RadarCard[]

  /**
   * Transition a card's status. `id` must exist; otherwise the result
   * is `Err("not-found")`. The new status need not be `"active"` —
   * any of the 4 arms is admissible (e.g. an operator may transition
   * a previously-dismissed card back to `"active"` for re-review).
   */
  setStatus(id: string, status: CardStatus): Result<RadarCard, RadarOpError>

  /**
   * Increment a card's `engagementCount` by 1. The card must exist
   * (`"not-found"`) and be `"active"` (`"not-active"`).
   */
  recordEngagement(id: string): Result<RadarCard, RadarOpError>

  /**
   * Mark every `"active"` card whose `createdAtMs < now - olderThanMs`
   * as `"expired"`. Returns the number of cards transitioned.
   * No cards are deleted; the queue size is preserved for downstream
   * inspection (compaction is a future ADR).
   */
  prune(olderThanMs: number, now: number): number
}
