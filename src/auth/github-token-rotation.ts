/**
 * ADR-0163 Phase E — mid-session GitHub token rotation.
 *
 * Cursor's `RefreshGithubAccessTokenInBackgroundComposer` rotates the GitHub
 * access token on a timer (well before the GitHub App token's 8-hour expiry)
 * so long-running sessions never hit a 401 during a `gh api` call. The
 * rotation is lock-protected (same {@link OAuthRefreshLockPort} from Phase D
 * so two CLI instances belonging to the same user do not double-rotate and
 * invalidate each other's refresh tokens).
 *
 * Closed-port discipline (DIP):
 *   - HTTP via `HttpClientPort` (reused from oidc-federation — same shape).
 *   - Clock via `ClockPort` (reused).
 *   - Lock via `OAuthRefreshLockPort` (from Phase D).
 *
 * No-heuristics discipline:
 *   - Default rotation threshold = 6 hours (matches GitHub App token's
 *     declared 8-hour TTL minus a 2-hour rotation budget — the value comes
 *     from GitHub's documented `expires_in: 28800` seconds). Caller can
 *     override via `rotateAfterMs`.
 *   - Default lock TTL = 30 seconds (the wire round-trip to
 *     github.com/login/oauth/access_token has a documented p99 of ~3 s; we
 *     allow 10x margin for the slowest observed). Caller can override.
 *
 * Negative invariants:
 *   - Never reads the lock state directly (no "is locked?" sneaky probes —
 *     always goes through `lockPort.tryAcquire`).
 *   - Never amplifies the returned token TTL (vendor's `expires_in` wins).
 *   - Lock release is in `finally` so an HTTP throw does not strand the lock.
 *
 * Plane-clean: imports only sibling ports (lock + oidc-federation HTTP/clock
 * types). No SDK, no `node:*`.
 */

import type { ClockPort, HttpClientPort } from "../llm/oidc-federation"
import type { OAuthRefreshLockPort } from "./oauth-refresh-lock"

/** A GitHub OAuth token pair carried across rotations. `expiresAt` is
 *  ms-since-epoch (vendor TTL applied to clock at issue time). `userId` is the
 *  GitHub user/app id — used as the lock key suffix so two CLI instances
 *  belonging to DIFFERENT users do not contend on the same lock. */
export interface GitHubTokenPair {
  readonly accessToken: string
  readonly refreshToken: string
  readonly expiresAt: number
  readonly userId: string
}

export interface RotateOptions {
  readonly current: GitHubTokenPair
  readonly clientId: string
  readonly clientSecret: string
  readonly httpPort: HttpClientPort
  readonly clockPort: ClockPort
  readonly lockPort: OAuthRefreshLockPort
  /** Override the rotation threshold. Default 6 hours (GitHub App token TTL
   *  is 8 h; we rotate at 6 h so a sudden 1-hour delay between rotate-check
   *  and next API call still has 1 h headroom). */
  readonly rotateAfterMs?: number
  /** Override the lock TTL. Default 30 seconds. */
  readonly lockTtlMs?: number
  /** Override the rotation endpoint base. Default `https://github.com`. */
  readonly endpointBase?: string
  /** Holder id for the lock. Default = a random uuid generated by the caller
   *  (we do NOT generate one — the no-heuristics discipline says: caller
   *  identity is caller's responsibility). REQUIRED non-empty. */
  readonly holderId: string
}

/** Discriminator for {@link RotateResult}. Six branches cover every observable
 *  outcome — caller switches on `.kind`, never on message text. */
export type RotateResult =
  /** Token was rotated. New pair carried in the result. */
  | { readonly kind: "rotated"; readonly next: GitHubTokenPair }
  /** Token was NOT rotated — current token still has more than rotateAfterMs
   *  of life. Returns the current pair verbatim (idempotent). */
  | { readonly kind: "not-needed"; readonly current: GitHubTokenPair }
  /** Another instance holds the lock. We skipped the rotation; caller may
   *  retry after a small backoff. */
  | { readonly kind: "skipped-locked" }
  /** Lock layer returned `redis-error` and no fallback resolved it. */
  | { readonly kind: "skipped-lock-error" }
  /** Refresh token rejected by GitHub (4xx). Caller MUST re-authenticate. */
  | { readonly kind: "refresh-rejected"; readonly httpStatus: number }
  /** Transient GitHub failure (5xx or network). Caller MAY retry. */
  | { readonly kind: "refresh-transient"; readonly httpStatus?: number; readonly cause?: unknown }
  /** GitHub's response was malformed (missing access_token / expires_in). */
  | { readonly kind: "refresh-malformed" }

/** Default constants — documented to vendor source. */
export const DEFAULT_ROTATE_AFTER_MS = 6 * 60 * 60 * 1000 // 6 hours
export const DEFAULT_LOCK_TTL_MS = 30 * 1000 // 30 seconds
export const DEFAULT_GITHUB_ENDPOINT_BASE = "https://github.com"

const LOCK_KEY_PREFIX = "gh-token-rotation:"

/** Lock-protected rotation. Pure function (no state across calls) — every
 *  call re-checks the token's expiry against the clock and re-acquires the
 *  lock. */
export const rotateGitHubToken = async (options: RotateOptions): Promise<RotateResult> => {
  if (options.holderId.length === 0) {
    throw new Error("rotateGitHubToken: holderId must be non-empty")
  }
  if (options.current.userId.length === 0) {
    throw new Error("rotateGitHubToken: current.userId must be non-empty")
  }
  if (options.clientId.length === 0 || options.clientSecret.length === 0) {
    throw new Error("rotateGitHubToken: clientId and clientSecret must be non-empty")
  }

  const rotateAfterMs = options.rotateAfterMs ?? DEFAULT_ROTATE_AFTER_MS
  const lockTtlMs = options.lockTtlMs ?? DEFAULT_LOCK_TTL_MS
  const endpointBase = options.endpointBase ?? DEFAULT_GITHUB_ENDPOINT_BASE

  const now = options.clockPort.now()
  const remainingMs = options.current.expiresAt - now

  // Early-out: token is still fresh. We rotate when remaining < rotateAfterMs
  // (NOT when total age > rotateAfterMs — that would require us to know the
  // issue time, which we do not carry). Practically: if the current token
  // has > 2h of life and rotateAfterMs is 6h, we rotate.
  // 2026-05-24 correction: the threshold MEANS "rotate when remaining is
  // less than this much" — i.e. start rotating well before expiry. So:
  // rotate IFF remaining < rotateAfterMs.
  if (remainingMs > rotateAfterMs) {
    return { kind: "not-needed", current: options.current }
  }

  const lockKey = `${LOCK_KEY_PREFIX}${options.current.userId}`
  let lockResult: Awaited<ReturnType<OAuthRefreshLockPort["tryAcquire"]>>
  try {
    lockResult = await options.lockPort.tryAcquire(lockKey, options.holderId, lockTtlMs)
  } catch (cause) {
    return { kind: "skipped-lock-error" }
  }

  if (lockResult === "would-wait" || lockResult === "would-acquire") {
    return { kind: "skipped-locked" }
  }
  if (lockResult === "redis-error") {
    return { kind: "skipped-lock-error" }
  }

  // Lock held — perform refresh. try/finally so any throw still releases.
  try {
    const body = {
      client_id: options.clientId,
      client_secret: options.clientSecret,
      grant_type: "refresh_token",
      refresh_token: options.current.refreshToken,
    }
    let response: { status: number; body: unknown }
    try {
      response = await options.httpPort.post(`${endpointBase}/login/oauth/access_token`, body, {
        "content-type": "application/json",
        accept: "application/json",
      })
    } catch (cause) {
      return { kind: "refresh-transient", cause }
    }

    if (response.status >= 500) {
      return { kind: "refresh-transient", httpStatus: response.status }
    }
    if (response.status >= 400) {
      return { kind: "refresh-rejected", httpStatus: response.status }
    }

    const parsed = response.body as {
      access_token?: unknown
      refresh_token?: unknown
      expires_in?: unknown
    }
    if (typeof parsed?.access_token !== "string" || parsed.access_token.length === 0) {
      return { kind: "refresh-malformed" }
    }
    if (typeof parsed.expires_in !== "number" || !Number.isFinite(parsed.expires_in) || parsed.expires_in <= 0) {
      return { kind: "refresh-malformed" }
    }
    // GitHub's refresh-token rotation may issue a NEW refresh token. Prefer
    // the new one when present; otherwise keep the current one (per GitHub
    // docs, if the response omits refresh_token, the old one is still valid).
    const nextRefresh =
      typeof parsed.refresh_token === "string" && parsed.refresh_token.length > 0
        ? parsed.refresh_token
        : options.current.refreshToken

    const nextExpiresAt = options.clockPort.now() + parsed.expires_in * 1000
    const next: GitHubTokenPair = {
      accessToken: parsed.access_token,
      refreshToken: nextRefresh,
      expiresAt: nextExpiresAt,
      userId: options.current.userId,
    }
    return { kind: "rotated", next }
  } finally {
    // Always release — even if the refresh threw. Holder-scoped so a stale
    // call from elsewhere cannot accidentally clear our lock.
    await options.lockPort.release(lockKey, options.holderId)
  }
}
