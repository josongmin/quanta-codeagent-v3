/**
 * Lima microVM backend — Phase 2 external-binary adapter (ADR-0160).
 *
 * Wraps the OSS `lima` CLI (macOS arm64/x64 + Linux). Each MCP server is
 * spawned **inside a Lima Linux guest** via `lima shell <vm> -- <argv>`.
 *
 * Architecture trade-off (documented; not silent):
 *   - **One VM per workspace** (NOT per-MCP). Lima VM cold-start is ~5–15s;
 *     creating a fresh VM for every MCP spawn would dominate latency. We
 *     reuse a single named VM (`quanta-skybridge-<hash(spec.id)>`) and
 *     shell-exec into it per spawn. The blast radius is "all MCPs on one
 *     host workspace share a kernel" — strictly weaker than per-MCP VM but
 *     strictly stronger than passthrough.
 *   - Per-MCP fresh VM is left to Phase 3 (ADR-0160 §Follow-up) when boot
 *     time can be amortized via VM image snapshots.
 *
 * Phase 2 = **external binary wrapper** (no Swift/Rust FFI). Phase 3 will
 * evaluate native Apple Virtualization framework bindings (Swift via Bun
 * FFI or napi-rs) for sub-second boot + vsock IPC.
 *
 * SOTA reference: Claude Desktop yukonSilver (proprietary). We mirror the
 * STRUCTURAL pattern (microVM + per-workspace reuse + stdio bridge as the
 * IPC fallback before vsock) with OSS tooling.
 */

import {
  type McpSandbox,
  type McpSandboxAvailability,
  type McpSandboxConfig,
  McpSandboxError,
  type McpSandboxHandle,
  type McpSandboxPolicy,
  type McpServerSpec,
  type SkybridgeRunner,
  type SkybridgeSpawner,
} from "./types"

/**
 * Detect Lima availability. Returns the binary path (treated as a version
 * proxy when no runner is wired) OR `null`. Pure probe — no side effects on
 * the host system.
 *
 * Resolution order:
 *   1. `cfg.which("lima")` — caller-injected (tests + future production wiring).
 *   2. `null` — when no `which` is wired we cannot probe safely; default to
 *      "not available" rather than importing `node:child_process` here. The
 *      production assembly layer is responsible for injecting `which`.
 */
export const detectLima = async (cfg: McpSandboxConfig = {}): Promise<string | null> => {
  const which = cfg.which
  if (which === undefined) return null
  const path = await which("lima")
  return path
}

/**
 * Deterministic VM name from a spec id. Lima VM names must be filesystem-
 * friendly (lowercase, hyphens, length-bounded). The hash is small and
 * collision-resistant enough for the workspace scope.
 */
export const limaVmName = (specId: string): string => {
  // FNV-1a 32-bit — tiny, deterministic, no crypto dep. Lima VM names are
  // workspace-local; we don't need cryptographic resistance.
  let h = 0x811c9dc5
  for (let i = 0; i < specId.length; i++) {
    h ^= specId.charCodeAt(i)
    h = Math.imul(h, 0x01000193) >>> 0
  }
  const tag = h.toString(16).padStart(8, "0")
  return `quanta-skybridge-${tag}`
}

/**
 * Compile a {@link McpSandboxPolicy} into a Lima YAML config + the runArgs
 * to launch the MCP server inside the VM. Pure — no side effects.
 *
 * The YAML follows Lima v0.21+ schema:
 *   - `cpus` / `memory` from policy (defaults 1 cpu / 512MiB).
 *   - `mounts` from hostReadAllowlist (ro) + hostWriteAllowlist (rw).
 *   - `networks` only when `policy.networkAllowlist` is non-empty — Lima
 *     itself has limited per-host policy (best-effort; doc-comment).
 *
 * `runArgs` is the argv to invoke after the VM is up:
 *   `["lima", "shell", "<vmName>", "--", ...spec.command]`
 * with `timeout <maxRuntimeMs>` prefix when policy.maxRuntimeMs is set (Lima
 * itself has no VM-level timeout primitive — we wrap via GNU/BSD `timeout`).
 */
export const compileLimaConfig = (
  policy: McpSandboxPolicy,
  spec: McpServerSpec,
): { limayaml: string; runArgs: string[] } => {
  const cpus = 1
  const memMiB = policy.memoryMb ?? 512
  const mounts: string[] = []

  // System read mount — give the guest read access to common system paths.
  // Lima default is full host mount; we narrow when allowlist is specified.
  if (policy.hostReadAllowlist !== undefined && policy.hostReadAllowlist.length > 0) {
    for (const p of policy.hostReadAllowlist) {
      mounts.push(`  - location: "${p}"\n    writable: false`)
    }
  } else {
    // Default: read-only system mount (no specific allowlist requested).
    mounts.push(`  - location: "/"\n    writable: false`)
  }
  if (policy.hostWriteAllowlist !== undefined && policy.hostWriteAllowlist.length > 0) {
    for (const p of policy.hostWriteAllowlist) {
      mounts.push(`  - location: "${p}"\n    writable: true`)
    }
  }

  const networksSection =
    policy.networkAllowlist !== undefined && policy.networkAllowlist.length > 0
      ? `networks:\n  # best-effort per-host policy; full MITM proxy is Phase 3\n${policy.networkAllowlist.map((h) => `  # allowed: ${h}`).join("\n")}\n  - lima: user-v2\n`
      : ""

  const limayaml = [
    `# quanta skybridge — Lima VM config for ${spec.id}`,
    `# Generated by compileLimaConfig() — do not hand-edit.`,
    `cpus: ${cpus}`,
    `memory: "${memMiB}MiB"`,
    `mounts:`,
    mounts.join("\n"),
    networksSection,
  ]
    .filter((s) => s.length > 0)
    .join("\n")

  const vmName = limaVmName(spec.id)
  const baseRun = ["lima", "shell", vmName, "--", ...spec.command]
  const runArgs =
    policy.maxRuntimeMs !== undefined
      ? ["timeout", `${Math.max(1, Math.floor(policy.maxRuntimeMs / 1000))}s`, ...baseRun]
      : baseRun

  return { limayaml, runArgs }
}

/**
 * Best-effort check: is the Lima VM already running? Returns false on any
 * uncertainty (causes a `lima start` attempt — `lima start` on an already-
 * running VM is a no-op, so the cost of a false-negative is bounded).
 */
const isVmRunning = async (
  vmName: string,
  runner: SkybridgeRunner | undefined,
): Promise<boolean> => {
  if (runner === undefined) return false
  try {
    const r = await runner(["lima", "list", "--json"])
    if (r.exitCode !== 0) return false
    // Each line is a JSON record. Parse permissively — Lima may emit either
    // one JSON-per-line or a JSON array; handle both.
    const lines = r.stdout.split("\n").filter((l) => l.trim().length > 0)
    for (const ln of lines) {
      try {
        const obj = JSON.parse(ln) as unknown
        if (
          obj !== null &&
          typeof obj === "object" &&
          "name" in obj &&
          (obj as { name: unknown }).name === vmName &&
          "status" in obj &&
          (obj as { status: unknown }).status === "Running"
        ) {
          return true
        }
      } catch {
        // ignore — not every line is JSON (e.g. legacy text mode)
      }
    }
    return false
  } catch {
    return false
  }
}

/** Probe binary + spawner presence; throw typed McpSandboxError on absence. */
const requireLimaWired = async (cfg: McpSandboxConfig): Promise<SkybridgeSpawner> => {
  const limaPath = await detectLima(cfg)
  if (limaPath === null) {
    throw new McpSandboxError(
      "backend-unavailable",
      "lima binary not found on PATH (install via `brew install lima` on macOS or your distribution package on Linux)",
    )
  }
  if (cfg.spawner === undefined) {
    throw new McpSandboxError(
      "backend-unavailable",
      "Lima backend requires a SkybridgeSpawner — none wired in McpSandboxConfig",
    )
  }
  return cfg.spawner
}

/** Best-effort VM bootstrap. Idempotent — skipped when already running or
 *  when no runner is wired (defer to lima itself). */
const ensureVmRunning = async (
  vmName: string,
  runner: SkybridgeRunner | undefined,
): Promise<void> => {
  if (runner === undefined) return
  const running = await isVmRunning(vmName, runner)
  if (running) return
  try {
    await runner(["lima", "start", vmName])
  } catch (e) {
    throw new McpSandboxError(
      "spawn-failed",
      `lima start failed: ${e instanceof Error ? e.message : String(e)}`,
      { cause: e },
    )
  }
}

const buildSpawnOpts = (
  spec: McpServerSpec,
): { cwd?: string; env?: Readonly<Record<string, string>> } => ({
  ...(spec.cwd !== undefined ? { cwd: spec.cwd } : {}),
  ...(spec.env !== undefined ? { env: spec.env } : {}),
})

const idempotentStop = (inner: { stop: () => Promise<void> }): (() => Promise<void>) => {
  let stopped = false
  return async () => {
    if (stopped) return
    stopped = true
    await inner.stop()
  }
}

/**
 * Lima-backed McpSandbox.
 *
 * `spawn`:
 *   1. Probe `lima` via cfg.which. Absent → throw
 *      `McpSandboxError("backend-unavailable", …)` (the caller is
 *      *explicitly* using the Lima backend; degradation is the registry's
 *      decision, not this adapter's).
 *   2. Resolve VM name from spec.id.
 *   3. If VM not running → `lima start <vmName>` (via runner).
 *   4. `cfg.spawner(["lima", "shell", <vm>, "--", ...spec.command], opts)`.
 *   5. Return a handle with `sandboxApplied=true`, `ipcChannel.kind="named-pipe"`
 *      (the Lima socket path), `backendId=<vmName>`.
 *
 * `stop`:
 *   - Stops the spawned shell process (per-MCP). Does NOT tear down the VM
 *     — the VM is workspace-scoped and reused by sibling MCPs. Operators
 *     manage VM lifecycle externally (`lima stop`/`lima delete`).
 */
export const limaMicroVmSandbox = (cfg: McpSandboxConfig = {}): McpSandbox => {
  return {
    async spawn(spec: McpServerSpec, policy: McpSandboxPolicy): Promise<McpSandboxHandle> {
      const spawner = await requireLimaWired(cfg)
      const vmName = limaVmName(spec.id)
      const { runArgs } = compileLimaConfig(policy, spec)
      await ensureVmRunning(vmName, cfg.runner)

      let raw: { pid: number; stop: () => Promise<void> }
      try {
        raw = await spawner(runArgs, buildSpawnOpts(spec))
      } catch (e) {
        throw new McpSandboxError(
          "spawn-failed",
          `lima shell spawn failed: ${e instanceof Error ? e.message : String(e)}`,
          { cause: e },
        )
      }

      // Lima exposes a socket per VM at ~/.lima/<vm>/ga.sock; we report it
      // as the named-pipe ref so callers that bypass stdio can locate it.
      return {
        serverId: spec.id,
        profile: policy.profile,
        backendId: vmName,
        sandboxApplied: true,
        ipcChannel: { kind: "named-pipe", ref: `lima-socket:${vmName}` },
        stop: idempotentStop(raw),
      }
    },

    async availability(): Promise<McpSandboxAvailability> {
      const limaPath = await detectLima(cfg)
      if (limaPath !== null) {
        return {
          backend: "microvm",
          warnings: [
            "Lima per-host network policy is best-effort; full MITM proxy is Phase 3",
            "VM lifecycle: one VM per workspace (shared across MCPs); per-MCP isolation is Phase 3",
          ],
        }
      }
      return {
        backend: "passthrough",
        warnings: [
          "lima not installed; install via `brew install lima` (macOS) or distribution package (Linux)",
        ],
      }
    },
  }
}
