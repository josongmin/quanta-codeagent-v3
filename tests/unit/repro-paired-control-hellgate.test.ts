/**
 * G2 paired-control — admission-filter hellgate.
 *
 * GAP (select.ts:245): the legacy admission filter keeps every sample whose
 * `outcome === "reproduced"`. A self-test that FAILS on the BASE tree is
 * admitted as a bug-reproducer even when the failure is a FALSE-RED — the
 * project does not import / the env is broken — so the symptom test FAILS for
 * a reason unrelated to the issue (the astropy-13033 shape: self-authored test
 * admitted on a broken base). The filter cannot tell a real base-FAIL from an
 * env/import-broken base-FAIL.
 *
 * G2: when the `paired-control` knob is ON, each sample carries a `baseControl`
 * verdict = did the happy/edge CONTROL tests (generated by the SAME repro-gen,
 * never the gold) PASS on the base tree?
 *   - "green"  ⇒ controls pass ⇒ env is healthy ⇒ a base-RED symptom is a REAL
 *                 reproduction. ADMIT.
 *   - "red"    ⇒ a control FAILED on base ⇒ env/import broken ⇒ the symptom's
 *                 base-RED is a FALSE-RED. REJECT.
 *   - "absent" ⇒ no control was run ⇒ cannot certify ⇒ REJECT (fail-closed).
 *
 * Tests below are TEETH:
 *   1. red-on-injection: inject an env-broken sample (controls RED) and prove
 *      that turning the gate ON flips the selection from admit → reject. If the
 *      reader site does not branch on `baseControl`, this test goes RED.
 *   2. default OFF byte-identical: the legacy filter must be untouched when the
 *      gate is off — proves the gate is the ONLY thing changing behavior.
 *   3. paired-control admits a clean reproducer (controls GREEN) — proves the
 *      gate is not a blanket "reject everything" no-op.
 *   4. projection wiring: `paired-control` knob ⇒ `benchPostureFromState`
 *      projects `pairedControl: true` (the read site the driver threads to
 *      `selectReproTest`'s `pairedControl` opt). Proves the knob is not a dead
 *      flag — its value reaches the admission layer's gate.
 */
import { describe, expect, test } from "bun:test"
import { selectReproTest } from "../../src/agent/repro-test/select"
import type { ReproTestSample } from "../../src/agent/repro-test/types"
import { benchPostureFromState, resolveBenchKnobs } from "../../src/runner/batch/eval/knobs-bench"

const mkSample = (
  source: string,
  outcome: ReproTestSample["outcome"],
  baseControl?: ReproTestSample["baseControl"],
): ReproTestSample => ({
  source,
  stdout: "",
  outcome,
  ...(baseControl !== undefined ? { baseControl } : {}),
})

describe("G2 paired-control admission filter", () => {
  // The astropy-13033 shape: the symptom test is base-RED (outcome
  // "reproduced") but it is a FALSE-RED — the project failed to import in the
  // exec env, so the control tests (which would PASS in a healthy env) FAIL on
  // base. Legacy filter admits it; paired-control must reject it.
  const envBroken = mkSample("def test_x():\n    assert thing() == 1", "reproduced", "red")
  // A genuine reproducer: base-RED symptom AND the happy/edge controls PASS on
  // base (env healthy) — a real bug.
  const realRepro = mkSample("def test_y():\n    assert thing() == 2", "reproduced", "green")

  test("legacy (gate OFF) admits the env-broken false-red — the bug being fixed", () => {
    const sel = selectReproTest([envBroken])
    // PROOF the gap exists: without the gate, the false-red is admitted.
    expect(sel.selected).not.toBeNull()
    expect(sel.reproducedCount).toBe(1)
  })

  test("RED-ON-INJECTION: gate ON rejects the env-broken false-red", () => {
    const off = selectReproTest([envBroken], { pairedControl: false })
    const on = selectReproTest([envBroken], { pairedControl: true })
    // The gate must FLIP the outcome — if the reader site ignores baseControl,
    // `on.selected` would still be non-null and this assertion FAILS.
    expect(off.selected).not.toBeNull()
    expect(on.selected).toBeNull()
    expect(on.controlRejectedCount).toBe(1)
  })

  test("gate ON admits a genuine reproducer (controls GREEN) — not a blanket reject", () => {
    const on = selectReproTest([realRepro], { pairedControl: true })
    expect(on.selected).not.toBeNull()
    expect(on.controlRejectedCount).toBe(0)
  })

  test("gate ON: among mixed samples, only the green-control reproducer survives", () => {
    const on = selectReproTest([envBroken, realRepro], { pairedControl: true })
    expect(on.selected).toBe(realRepro.source)
    expect(on.controlRejectedCount).toBe(1)
  })

  test("gate ON: 'absent' control (no control run) is fail-closed rejected", () => {
    const noControl = mkSample("def test_z():\n    assert q() == 9", "reproduced", "absent")
    const on = selectReproTest([noControl], { pairedControl: true })
    expect(on.selected).toBeNull()
    expect(on.controlRejectedCount).toBe(1)
  })

  test("gate ON: a sample with no baseControl field at all is fail-closed rejected", () => {
    const legacyShape = mkSample("def test_w():\n    assert r() == 0", "reproduced")
    const on = selectReproTest([legacyShape], { pairedControl: true })
    expect(on.selected).toBeNull()
  })
})

describe("G2 paired-control knob projection (wiring-proof)", () => {
  test("knob OFF ⇒ posture.pairedControl false", () => {
    const state = resolveBenchKnobs({ envVars: {} })
    const posture = benchPostureFromState(state, {} as NodeJS.ProcessEnv)
    expect(posture.pairedControl).toBe(false)
  })

  test("QUANTA_BENCH_PAIRED_CONTROL=1 ⇒ posture.pairedControl true", () => {
    const state = resolveBenchKnobs({
      envVars: { QUANTA_BENCH_PAIRED_CONTROL: "1" } as NodeJS.ProcessEnv,
    })
    const posture = benchPostureFromState(state, {} as NodeJS.ProcessEnv)
    // If the knob does not register / project, this is `undefined` and FAILS.
    expect(posture.pairedControl).toBe(true)
  })
})
