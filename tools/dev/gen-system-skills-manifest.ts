/**
 * Generator for `src/skill/system-skills/manifest.generated.ts`.
 *
 * WHY THIS EXISTS. `systemSkillsDir()` derived a path from `import.meta.url` and
 * `discoverSystemSkills()` then `readdir`'d it. That works from source and is
 * empty in a `bun build --compile` binary, where the path resolves to
 * `/$bunfs/root` — so the shipped CLI silently offered ZERO bundled skills.
 *
 * A directory cannot be embedded, but a FILE can: `import x from "./y/SKILL.md"
 * with { type: "file" }` makes bun carry the bytes and hand back a path that
 * resolves in both modes. The generated module is that list — one import per
 * skill, which is exactly the directory listing expressed as something the
 * bundler can see.
 *
 * The manifest is GENERATED, not hand-kept, and a drift test regenerates it and
 * compares: a skill added to the tree without regenerating fails there rather
 * than silently vanishing from the shipped binary — which is the failure mode
 * this whole change exists to remove.
 *
 * Usage: `bun run tools/dev/gen-system-skills-manifest.ts [--check]`
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const REPO_ROOT = new URL("../../", import.meta.url).pathname
const SKILLS_DIR = join(REPO_ROOT, "src/skill/system-skills")
const OUT = join(SKILLS_DIR, "manifest.generated.ts")

/** Every `<name>/SKILL.md` directory, sorted for a deterministic file. */
export const systemSkillNames = (dir: string = SKILLS_DIR): string[] =>
  readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .filter((e) => {
      try {
        readFileSync(join(dir, e.name, "SKILL.md"))
        return true
      } catch {
        return false
      }
    })
    .map((e) => e.name)
    .sort()

const ident = (name: string): string => `skill_${name.replace(/[^A-Za-z0-9]/g, "_")}`

export const renderManifest = (names: readonly string[]): string => {
  const imports = names
    .map((n) => `import ${ident(n)} from "./${n}/SKILL.md" with { type: "file" }`)
    .join("\n")
  const rows = names.map((n) => `  { name: ${JSON.stringify(n)}, path: ${ident(n)} },`).join("\n")
  return `// GENERATED by tools/dev/gen-system-skills-manifest.ts — do not edit.
//
// Each entry EMBEDS its SKILL.md via bun's file-import attribute, so the bytes
// travel inside a \`bun build --compile\` binary and the path resolves in both
// modes (a real path in dev, \`/$bunfs/root/…\` when compiled). A \`readdir\` of
// the source tree cannot do that: the directory does not exist in the artifact.

${imports}

export interface SystemSkillAsset {
  readonly name: string
  readonly path: string
}

export const SYSTEM_SKILL_ASSETS: readonly SystemSkillAsset[] = [
${rows}
]
`
}

if (import.meta.main) {
  const names = systemSkillNames()
  const next = renderManifest(names)
  if (process.argv.includes("--check")) {
    const current = (() => {
      try {
        return readFileSync(OUT, "utf8")
      } catch {
        return ""
      }
    })()
    if (current !== next) {
      process.stdout.write(
        "[gen-system-skills-manifest] STALE — run `bun run tools/dev/gen-system-skills-manifest.ts`\n",
      )
      process.exit(1)
    }
    process.stdout.write(`[gen-system-skills-manifest] up to date: ${names.length} skills\n`)
  } else {
    writeFileSync(OUT, next, "utf8")
    process.stdout.write(`[gen-system-skills-manifest] wrote ${names.length} skills\n`)
  }
}
