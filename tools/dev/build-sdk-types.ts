/**
 * `bun run build:sdk:types` — produce the consumer-facing `.d.ts` for the
 * `quanta-codeagent/sdk` export (jul-4 P8), with NO extra tooling (tsc only,
 * no api-extractor / dts bundlers, no hand-rolled specifier rewriting).
 *
 * WHY two tsc passes: `tsconfig.base.json` uses `@/*` path aliases and tsc
 * never rewrites aliases in declaration emit — a plain `--emitDeclarationOnly`
 * tree leaves `from "@/ipc/session"` in the output, which an external consumer
 * cannot resolve (the exact reason USAGE-sdk-door §9 needed the paths shim).
 * tsc DOES rewrite specifiers in `--outFile` declaration bundles (it computes
 * ambient `declare module "<rootDir-relative>"` names and rewrites all
 * intra-bundle imports to them). But `--outFile` can't run straight off the
 * sources (module=system forbids `import.meta` json-attribute imports etc.),
 * and tsc does not re-emit `.d.ts` INPUTS into a bundle. So:
 *
 *   pass A  tsc -p tsconfig.sdk-dts.json      → dist/sdk/types/** (alias-bearing
 *           tree; ALSO the full-graph typecheck gate, exit!=0 aborts)
 *   stage   dist/sdk/types/**·*.d.ts → dist/sdk/stage/**·*.ts (byte-identical
 *           copies, renamed so tsc treats them as emittable inputs; the two
 *           ambient module decls for untyped deps are staged alongside)
 *   pass B  tsc -p tsconfig.sdk-dts-bundle.json → dist/sdk/quanta-sdk-modules.d.ts
 *           (single ambient-module bundle, all `@/*` rewritten by tsc itself)
 *   entry   dist/sdk/index.d.ts (reference + re-export of the door module)
 *
 * Consumers then need NO paths shim, NO ambient `files`, NO bun-types — see
 * USAGE-sdk-door §9 and the acceptance proof in the jul-4 P8 report.
 */
import { spawnSync } from "node:child_process"
import { existsSync } from "node:fs"
import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const repoRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))))
const tscBin = process.env["QUANTA_TSC_BIN"] ?? join(repoRoot, "node_modules/.bin/tsc")

const typesDir = join(repoRoot, "dist/sdk/types")
const stageDir = join(repoRoot, "dist/sdk/stage")
const bundleFile = join(repoRoot, "dist/sdk/quanta-sdk-modules.d.ts")
const entryFile = join(repoRoot, "dist/sdk/index.d.ts")

/** Ambient `declare module` files for untyped runtime deps — staged as scripts
 *  so their declarations land INSIDE the bundle (a consumer then resolves
 *  `import ... from "turndown"` without any ambient-file loading). */
const AMBIENT_DECLS = [
  "src/agent/sticky-model/write-file-atomic.d.ts",
  "src/tool/web/turndown.d.ts",
] as const

const tsc = (project: string): void => {
  const res = spawnSync(tscBin, ["-p", join(repoRoot, project)], {
    cwd: repoRoot,
    stdio: "inherit",
  })
  if (res.status !== 0) {
    throw new Error(`tsc -p ${project} failed (exit ${res.status ?? "signal"})`)
  }
}

const stageTree = async (dir: string): Promise<number> => {
  let staged = 0
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name)
    if (entry.isDirectory()) {
      staged += await stageTree(abs)
      continue
    }
    if (!entry.name.endsWith(".d.ts")) continue
    const rel = relative(typesDir, abs)
    const dest = join(stageDir, rel.slice(0, -".d.ts".length) + ".ts")
    await mkdir(dirname(dest), { recursive: true })
    await copyFile(abs, dest)
    staged += 1
  }
  return staged
}

const ENTRY = `// GENERATED by \`bun run build:sdk:types\` — do not edit.
// Types entry for the \`quanta-codeagent/sdk\` export. The sibling
// \`quanta-sdk-modules.d.ts\` is a tsc \`--outFile\` declaration bundle whose
// modules are declared under the \`dist/sdk/stage/*\` namespace; this file pulls
// the bundle into the consumer's program and re-exports the SDK door.
/// <reference path="./quanta-sdk-modules.d.ts" />
export * from "dist/sdk/stage/sdk/index";
`

const main = async (): Promise<void> => {
  await rm(typesDir, { recursive: true, force: true })
  await rm(stageDir, { recursive: true, force: true })
  await rm(bundleFile, { force: true })
  await rm(entryFile, { force: true })

  tsc("tsconfig.sdk-dts.json") // pass A — tree emit + full-graph typecheck gate

  const staged = await stageTree(typesDir)
  const ambientDest = join(stageDir, "__ambient__")
  await mkdir(ambientDest, { recursive: true })
  for (const decl of AMBIENT_DECLS) {
    const base = decl.slice(decl.lastIndexOf("/") + 1) // e.g. turndown.d.ts
    await copyFile(
      join(repoRoot, decl),
      join(ambientDest, base.slice(0, -".d.ts".length) + ".ts"),
    )
  }

  tsc("tsconfig.sdk-dts-bundle.json") // pass B — alias-free ambient bundle

  if (!existsSync(bundleFile)) throw new Error(`bundle missing after pass B: ${bundleFile}`)
  await writeFile(entryFile, ENTRY)

  // The intermediates are not part of the artifact — the shipped surface is
  // exactly { dist/sdk/index.d.ts, dist/sdk/quanta-sdk-modules.d.ts }.
  await rm(typesDir, { recursive: true, force: true })
  await rm(stageDir, { recursive: true, force: true })

  console.log(`build:sdk:types OK — ${staged} modules bundled into dist/sdk/quanta-sdk-modules.d.ts`)
}

await main()
